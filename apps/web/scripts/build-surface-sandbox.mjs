/**
 * Generate `public/surface-sandbox/frame.html`, the document that executes authored Surface code.
 *
 * The React runtime is bundled and *inlined*, not linked: the frame runs in an opaque origin under
 * a policy that names no host, so a `<script src>` — even a same-origin one — is refused. React 19
 * ships no UMD build, which is the other half of the same conclusion.
 *
 * Run before `vite build` and before `vite dev`, since Vite serves `public/` verbatim in both.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(app, "public", "surface-sandbox");

const bundle = await build({
  entryPoints: [join(app, "surface-sandbox", "runtime.tsx")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
  define: { "process.env.NODE_ENV": '"production"' },
  loader: { ".tsx": "tsx" },
});

const runtime = bundle.outputFiles[0]?.text;
if (!runtime) throw new Error("surface sandbox runtime produced no output");
if (runtime.includes("</script")) throw new Error("bundle would terminate its own script tag");

const html = `<!doctype html>
<!--
  Generated by scripts/build-surface-sandbox.mjs — edit surface-sandbox/runtime.tsx instead.

  This document executes agent-authored Surface view code. It is embedded under
  \`sandbox="allow-scripts"\` with no \`allow-same-origin\`, so it holds an opaque origin: no access to
  the host page, its cookies, or its storage. \`connect-src 'none'\` leaves it no network. Those two
  facts are the security boundary; nothing else here is.

  \`frame-ancestors\` is ignored in a meta CSP, so the API sends it as a header — see
  SURFACE_SANDBOX_CSP in packages/surface/src/sandbox.ts.
-->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta
      http-equiv="content-security-policy"
      content="default-src 'none'; script-src 'unsafe-inline' 'unsafe-eval'; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none'; form-action 'none'; base-uri 'none'"
    />
    <title>Surface code view</title>
    <style>
      html, body { margin: 0; padding: 0; background: transparent; color: #111827;
        font: 14px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }
      #error { padding: 12px; border-radius: 8px; background: #fef2f2; color: #991b1b; }
    </style>
  </head>
  <body>
    <div id="root"></div>
    <script>${runtime}</script>
  </body>
</html>
`;

await mkdir(out, { recursive: true });
await writeFile(join(out, "frame.html"), html, "utf8");
