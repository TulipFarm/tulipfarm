// Codegen: inline the Chart.js UMD as a TS string const for the A2UI iframe.
//
// The A2UI iframe runs under a strict CSP (`default-src 'none'; connect-src 'none'`) so Chart.js
// cannot load from a CDN — it must be injected as a nonce'd inline <script>. We ship the UMD as a
// JSON.stringify'd string const (test-safe, survives bundling) rather than a `?raw` import, matching
// the existing audited-string pattern (A2UI_RUNTIME, A2UI_COMPONENT_CSS).
//
// Run from the apps/web cwd:  node scripts/gen-chart-source.mjs   (npm: `pnpm gen:chart-source`)
// Re-run on a chart.js version bump. The output is committed so clean checkouts typecheck/build.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "..");

const umdPath = resolve(webRoot, "node_modules/chart.js/dist/chart.umd.js");
const outPath = resolve(webRoot, "app/lib/a2ui/chart-source.ts");

const umd = readFileSync(umdPath, "utf8");

// The const is injected inline as `<script>...</script>` in srcdoc.ts. A literal `</script>` in the
// bundle would terminate that block early (breakage / injection surface). Enforce the invariant here
// so a future chart.js bump can't silently reintroduce it. (v4.5.1 is clean — grep-verified.)
if (/<\/script/i.test(umd)) {
  throw new Error(
    "Chart.js UMD contains '</script>' — inline injection in srcdoc.ts would break; escape needed before inlining."
  );
}

const banner =
  "// GENERATED by scripts/gen-chart-source.mjs — do not edit by hand.\n" +
  "// Chart.js UMD, inlined as a string for nonce'd injection into the A2UI iframe (CSP: no CDN).\n" +
  "// Re-run `pnpm gen:chart-source` after a chart.js version bump.\n";

const body = `${banner}\nexport const CHART_JS_SOURCE = ${JSON.stringify(umd)};\n`;

writeFileSync(outPath, body, "utf8");

const versionMatch = umd.match(/Chart\.js v[\d.]+/);
console.log(
  `wrote ${outPath} (${(body.length / 1024).toFixed(0)}KB, ${versionMatch?.[0] ?? "unknown version"})`
);
