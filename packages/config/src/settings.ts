export const settingServices = ['api', 'worker', 'storage-worker', 'snippet-broker', 'database', 'compose'] as const;
export type SettingService = (typeof settingServices)[number];

/**
 * - required: every deployment must set it.
 * - production: required when NODE_ENV=production; development has a fallback.
 * - conditional: required only when the related feature is configured.
 * - optional: has a default or turns a feature off when unset.
 */
export type SettingRequirement = 'required' | 'production' | 'conditional' | 'optional';

