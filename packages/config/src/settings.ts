export type Setting = {
  readonly name: string;
  readonly group: SettingGroup;
  readonly services: readonly SettingService[];
  readonly requirement: SettingRequirement;
  /** Secret values must come from a secret store; application secrets also accept <NAME>_FILE. */
  readonly secret: boolean;
  readonly default?: string;
  readonly description: string;
  /** Overrides the requirement label in the operator table, such as "One sign-in method". */
  readonly requirementNote?: string;
  /** Compose containers or build steps, when they differ from the application services. */
  readonly usedBy?: string;
  /** Written by `self-host:setup` into the per-service env files. */
  readonly generated?: true;
  /** Listed in self-host/.env.example. */
  readonly selfHost?: {
    readonly section: SelfHostSection;
    readonly example?: string;
    readonly commented?: boolean;
    readonly comment?: string;
  };
};

