function keyring(prefix: string, protects: string, services: readonly SettingService[], generated: boolean): Setting[] {
  const shared = { group: 'Encryption keys', services, ...(generated ? ({ generated: true } as const) : {}) } as const;
  return [
    {
      ...shared,
      name: `${prefix}_KEY_ID`,
      requirement: 'production',
      secret: false,
      description: `Current key ID for ${protects}. Stored with each ciphertext.`,
    },
    {
      ...shared,
      name: `${prefix}_KEY`,
      requirement: 'production',
      secret: true,
      description: `Current AES-256-GCM key for ${protects}: 64 hexadecimal characters.`,
    },
    {
      ...shared,
      name: `${prefix}_PREVIOUS_KEYS`,
      requirement: 'optional',
      secret: true,
      description: `JSON map of retired key IDs to keys for ${protects}. Used only to decrypt.`,
    },
  ];
}

function oauthClient(
  prefix: string,
  product: string,
  group: SettingGroup,
  services: readonly SettingService[],
  scopes: boolean,
): Setting[] {
  const shared = { group, services, requirement: 'conditional' } as const;
  return [
    {
      ...shared,
      name: `${prefix}_CLIENT_ID`,
      secret: false,
      description: `${product} OAuth client ID. Unset disables ${product}.`,
    },
    { ...shared, name: `${prefix}_CLIENT_SECRET`, secret: true, description: `${product} OAuth client secret.` },
    {
      ...shared,
      name: `${prefix}_REDIRECT_URI`,
      secret: false,
      description: `${product} OAuth callback URL registered with the provider.`,
    },
    ...(scopes
      ? [
          {
            ...shared,
            name: `${prefix}_SCOPES`,
            secret: false,
            description: `Space-separated ${product} OAuth scopes.`,
          },
        ]
      : []),
  ];
}

