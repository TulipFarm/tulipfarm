import { selfHostSections, settingGroups, settings, type Setting } from './settings.ts';

// Pure renderers for the documents generated from the settings registry.
// packages/config/scripts/config-docs.mjs writes them; a tooling test checks freshness.

const requirementLabels = {
  required: 'Yes',
  production: 'Production',
  conditional: 'Conditional',
  optional: 'No',
} as const;
const code = (value: string) => `\`${value}\``;
const cell = (value: string) => value.replaceAll('|', '\\|');

export function renderEnvExample(entries: readonly Setting[] = settings): string {
  const lines = [
    '# Generated by `pnpm config:docs` from packages/config/src/settings.ts. Do not edit.',
    '# Copy to self-host/.env, or provide the same names from your secret store.',
    '# Compose reads the shell environment first, then this file. Values containing $',
    '# must be single-quoted here. See https://docs.tulipfarm.ai/self-hosting/secrets/',
  ];
  for (const [section, comments] of Object.entries(selfHostSections)) {
    const rows = entries.filter(entry => entry.selfHost?.section === section);
    if (rows.length === 0) continue;
    lines.push('', ...comments.map(comment => `# ${comment}`));
    for (const entry of rows) {
      if (entry.selfHost?.comment) lines.push(`# ${entry.selfHost.comment}`);
      lines.push(`${entry.selfHost?.commented ? '# ' : ''}${entry.name}=${entry.selfHost?.example ?? ''}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

export function renderOperatorTable(entries: readonly Setting[] = settings): string {
  const rows = entries
    .filter(entry => entry.selfHost)
    .map(entry => [
      code(entry.name),
      entry.requirementNote ?? requirementLabels[entry.requirement],
      entry.usedBy ?? entry.services.join(', '),
      cell(entry.default === undefined ? entry.description : `${entry.description} Default ${code(entry.default)}.`),
    ]);
  return table(['Name', 'Required', 'Used by', 'Purpose'], rows);
}

export function renderReference(entries: readonly Setting[] = settings): string {
  const sections: string[] = [];
  for (const group of settingGroups) {
    const rows = entries.filter(entry => entry.group === group);
    if (rows.length === 0) continue;
    sections.push(
      `### ${group}\n\n${table(
        ['Name', 'Services', 'Required', 'Secret', 'Default', 'Description'],
        rows.map(entry => [
          code(entry.name) + (entry.generated ? ' (generated)' : ''),
          entry.usedBy ? `Compose: ${entry.usedBy}` : entry.services.join(', '),
          requirementLabels[entry.requirement],
          entry.secret ? 'Yes' : 'No',
          entry.default === undefined ? '' : code(entry.default),
          cell(entry.description),
        ]),
      )}`,
    );
  }
  return sections.join('\n\n');
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map(row => `| ${row.join(' | ')} |`),
  ].join('\n');
}

/** Replaces the text between `<!-- BEGIN GENERATED: id -->` and `<!-- END GENERATED: id -->`. */
export function replaceGeneratedBlock(document: string, id: string, content: string): string {
  const begin = `<!-- BEGIN GENERATED: ${id} -->`;
  const end = `<!-- END GENERATED: ${id} -->`;
  const start = document.indexOf(begin);
  const finish = document.indexOf(end);
  if (start === -1 || finish < start) throw new Error(`Generated block ${id} is missing`);
  return `${document.slice(0, start + begin.length)}\n${content}\n${document.slice(finish)}`;
}

export function renderConfigurationDocument(document: string, entries: readonly Setting[] = settings): string {
  return replaceGeneratedBlock(
    replaceGeneratedBlock(document, 'operator-settings', renderOperatorTable(entries)),
    'variable-reference',
    renderReference(entries),
  );
}
